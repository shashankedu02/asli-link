"""Run the checker over eval/cases.csv and write docs/EVALUATION.md plus eval/results.json.

Usage: python scripts/evaluate.py          (writes both files)
       python scripts/evaluate.py --check  (exit 1 if the committed results differ from a fresh run)

Outcome per case, from the checker's verdict:
  official -> "official"; impersonation_signals -> "flagged"; cannot_check -> "cannot_check";
  not_recognised -> "not_recognised". The checker never says "safe", and neither does this report.
No clock or random input: the same cases and registry always give the same numbers.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from asli.checker import Checker, Verdict  # noqa: E402

CASES = ROOT / "eval" / "cases.csv"
RESULTS = ROOT / "eval" / "results.json"
REPORT = ROOT / "docs" / "EVALUATION.md"

OUTCOME = {
    Verdict.OFFICIAL: "official",
    Verdict.IMPERSONATION: "flagged",
    Verdict.CANNOT_CHECK: "cannot_check",
    Verdict.NOT_RECOGNISED: "not_recognised",
}


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def run() -> dict:
    checker = Checker()
    rows = list(csv.DictReader(CASES.open(encoding="utf-8")))
    cases = []
    for row in rows:
        result = checker.check_message(row["text"])
        outcome = OUTCOME[result.verdict] if result.verdict else "no_link_found"
        cases.append({**row, "outcome": outcome})
    return {"registry_version": checker.registry.version, "n_cases": len(cases), "cases": cases}


def summarise(data: dict) -> dict:
    cases = data["cases"]

    def cell(subset, outcome):
        return sum(1 for c in subset if c["outcome"] == outcome)

    out: dict = {"by_provenance_truth": {}, "by_category": {}, "failures": []}
    groups = defaultdict(list)
    for c in cases:
        groups[(c["provenance"], c["truth"])].append(c)
        out["by_category"].setdefault(f"{c['truth']}/{c['category']}", Counter())[c["outcome"]] += 1
    for (prov, truth), subset in sorted(groups.items()):
        out["by_provenance_truth"][f"{prov}/{truth}"] = {"n": len(subset), **Counter(c["outcome"] for c in subset)}
    out["by_category"] = {k: dict(v) for k, v in sorted(out["by_category"].items())}
    for c in cases:
        t, o = c["truth"], c["outcome"]
        bad = (
            (t == "impostor" and o != "flagged")
            or (t == "official" and o != "official")
            or (t == "benign" and o in ("flagged", "official"))
            or (t == "hidden" and o != "cannot_check")
            or (t == "out_of_scope" and o in ("official",))
        )
        if bad:
            out["failures"].append(
                {
                    "id": c["id"],
                    "text": c["text"],
                    "truth": t,
                    "category": c["category"],
                    "provenance": c["provenance"],
                    "outcome": o,
                }
            )
    out["impostor_judged_official"] = sum(
        1 for c in cases if c["truth"] in ("impostor", "out_of_scope") and c["outcome"] == "official"
    )
    return out


def pct(k: int, n: int) -> str:
    lo, hi = wilson(k, n)
    return f"{k}/{n} = {100 * k / n:.1f}% (95% CI {100 * lo:.1f}-{100 * hi:.1f}%)" if n else "n/a"


def report(data: dict, s: dict) -> str:
    cases = data["cases"]
    pick = lambda prov, truth: [c for c in cases if c["provenance"] == prov and c["truth"] == truth]  # noqa: E731
    syn = pick("synthetic_impostor", "impostor")
    hand_imp = pick("handwritten", "impostor")
    off = pick("registry_official", "official")
    benign = pick("handwritten", "benign")
    hidden = pick("handwritten", "hidden")
    oos = pick("handwritten", "out_of_scope")
    n = lambda subset, o: sum(1 for c in subset if c["outcome"] == o)  # noqa: E731
    lines = [
        "# Evaluation",
        "",
        "_Generated by `python scripts/evaluate.py`. Do not edit by hand; `--check` fails if this file is stale._",
        "",
        f"Registry version: `{data['registry_version']}` · Cases: {data['n_cases']} (`eval/cases.csv`, built by `eval/build_cases.py`)",
        "",
        "## What these numbers are, and are not",
        "",
        "- The case set is **small and mostly synthetic**. Impostor cases are generated from the registry by rules that mirror "
        "the signals the checker looks for, so those results are **optimistic**: they show the rules fire as designed, "
        "not how the checker would do on phishing seen in the wild.",
        "- There is **no sample of real phishing links** here. A real-world detection rate has not been measured.",
        "- Intervals are Wilson 95% intervals and are wide at these sizes.",
        "- The checker never calls a link safe. `not_recognised` means no claim could be established.",
        "",
        "## Results",
        "",
        "| Group (ground truth) | Outcome measured | Result |",
        "|---|---|---|",
        f"| Official domains from the registry (consistency) | judged `official` | {pct(n(off, 'official'), len(off))} |",
        f"| Synthetic impostors (optimistic) | `flagged` | {pct(n(syn, 'flagged'), len(syn))} |",
        f"| Handwritten impostors | `flagged` | {pct(n(hand_imp, 'flagged'), len(hand_imp))} |",
        f"| Benign links, some containing brand words | wrongly `flagged` | {pct(n(benign, 'flagged'), len(benign))} |",
        f"| Shorteners | `cannot_check` | {pct(n(hidden, 'cannot_check'), len(hidden))} |",
        f"| Unbranded phishing (out of scope by design) | `flagged` | {pct(n(oos, 'flagged'), len(oos))}; `not_recognised` {n(oos, 'not_recognised')} |",
        "",
        f"**Safety invariant:** impostor or out-of-scope phishing judged `official`: **{s['impostor_judged_official']}** "
        f"of {len(syn) + len(hand_imp) + len(oos)}.",
        "",
        "## Outcomes by category",
        "",
        "| truth/category | outcomes |",
        "|---|---|",
    ]
    for k, v in s["by_category"].items():
        lines.append(f"| {k} | {', '.join(f'{o}: {c}' for o, c in sorted(v.items()))} |")
    lines += ["", "## Every case that did not match its label", ""]
    if s["failures"]:
        lines += ["| id | truth | category | outcome | text |", "|---|---|---|---|---|"]
        for f in s["failures"]:
            lines.append(f"| {f['id']} | {f['truth']} | {f['category']} | {f['outcome']} | `{f['text']}` |")
    else:
        lines.append("None.")
    lines += [
        "",
        "## Known limits",
        "",
        "- Phishing that names no known entity and uses a neutral domain gives `not_recognised`. That is the intended abstention, not a detection.",
        "- Entities outside the registry cannot be claimed or impersonated in this model.",
        "- Official domains can be compromised; `official` says who owns the domain, not that a page or request is legitimate.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    data = run()
    s = summarise(data)
    new_json = (
        json.dumps(
            {
                "registry_version": data["registry_version"],
                "n_cases": data["n_cases"],
                "summary": s,
                "cases": data["cases"],
            },
            indent=1,
            sort_keys=True,
        )
        + "\n"
    )
    new_report = report(data, s)
    if args.check:
        same = (
            RESULTS.exists()
            and RESULTS.read_text(encoding="utf-8") == new_json
            and REPORT.exists()
            and REPORT.read_text(encoding="utf-8") == new_report
        )
        print("up to date" if same else "STALE: rerun scripts/evaluate.py")
        return 0 if same else 1
    RESULTS.write_text(new_json, encoding="utf-8")
    REPORT.write_text(new_report, encoding="utf-8")
    print(new_report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
